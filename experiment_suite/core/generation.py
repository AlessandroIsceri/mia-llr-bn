import numpy as np
import networkx as nx

from pgmpy.models import DiscreteBayesianNetwork
from pgmpy.factors.discrete import TabularCPD
from pgmpy.sampling import BayesianModelSampling

def generate_simple_bn(n_nodes, n_modmin, n_modmax, np_rng):
    """
    Build a simple Bayesian Network with structure:

        X0, X1, ..., Xn -> Y

    Each variable is discrete with random cardinality in [n_modmin, n_modmax].
    """

    parents = [f"X{i}" for i in range(n_nodes - 1)]

    edges = (
        [(parent, "Y") for parent in parents]
    )

    bn = DiscreteBayesianNetwork(edges)

    cardinality_dict = {}

    # Generate CPDs for all root nodes
    for node in parents:
        n_modes = np_rng.integers(n_modmin, n_modmax + 1)
        cardinality_dict[node] = n_modes

        cpd = sample_cpd(
            variable=node,
            variable_card=n_modes,
            parents=[],
            evidence_card=[],
            np_rng=np_rng
        )

        bn.add_cpds(cpd)
        
    # Generate CPD for target variable Y
    y_card = np_rng.integers(n_modmin, n_modmax + 1)
    cardinality_dict["Y"] = y_card
    cpd_y = sample_cpd(
        variable="Y",
        variable_card=y_card,
        parents=parents,
        evidence_card=[cardinality_dict[p] for p in parents],
        np_rng=np_rng
    )

    bn.add_cpds(cpd_y)

    assert bn.check_model()
    return bn, cardinality_dict

def try_generate_dag(n_nodes, target_edges, max_parents, np_rng):

    # Random topological order
    perm = np_rng.permutation(n_nodes).tolist()

    adj = np.zeros((n_nodes, n_nodes), dtype=int)
    parents_count = np.zeros(n_nodes, dtype=int)
    edges_placed = 0

    # Build a spanning tree -> guarantees weak connectivity by construction
    for k in range(1, n_nodes):
        child = perm[k]
        candidates = [perm[i] for i in range(k) if parents_count[child] < max_parents]
        if not candidates:
            return None
        parent = perm[int(np_rng.integers(0, len(candidates)))]
        adj[parent, child] = 1
        parents_count[child] += 1
        edges_placed += 1

    # Add remaining edges
    extra_candidates = [
        (perm[i], perm[j])
        for i in range(n_nodes)
        for j in range(i + 1, n_nodes)
        if adj[perm[i], perm[j]] == 0
    ]
    np_rng.shuffle(extra_candidates)

    for parent, child in extra_candidates:
        if edges_placed == target_edges:
            break
        if parents_count[child] < max_parents:
            adj[parent, child] = 1
            parents_count[child] += 1
            edges_placed += 1

    if edges_placed < target_edges:
        return None

    return adj

def generate_realistic_bn(
    n_nodes,
    ratio_arc,
    n_modmin,
    n_modmax,
    np_rng,
    max_parents=3,
    max_retries=100000,
):
    """
    Generate a random discrete Bayesian Network whose DAG satisfies:
      - exactly n_nodes * ratio_arc directed edges
      - at most max_parents parents per node
      - weak connectivity

    The DAG is generated by first sampling a random topological ordering and
    constructing a spanning tree, which guarantees weak connectivity by
    construction. Additional edges are then added randomly while respecting
    the maximum number of parents per node and the target number of edges.

    If a valid DAG cannot be generated within max_retries attempts, the
    function raises a RuntimeError.
    """

    target_edges = int(round(n_nodes * ratio_arc))

    # Retry DAG generation until a valid weakly connected graph is found
    adj = None
    for _ in range(1, max_retries + 1):
        adj = try_generate_dag(n_nodes, target_edges, max_parents, np_rng)
        if adj is not None:
            break  # Valid weakly connected DAG found

    if adj is None:
        raise RuntimeError(
            f"Could not generate a connected DAG after {max_retries} attempts. "
            "Consider increasing ratio_arc or max_parents."
        )

    # Build pgmpy BayesianNetwork from the adjacency matrix
    node_names = [f"V{i}" for i in range(n_nodes)]

    final_edges = [
        (node_names[i], node_names[j])
        for i in range(n_nodes)
        for j in range(n_nodes)
        if adj[i, j] == 1
    ]

    bn = DiscreteBayesianNetwork(final_edges)

    # Ensure every node is present 
    for name in node_names:
        if name not in bn.nodes():
            bn.add_node(name)

    # Sample CPDs in topological order
    causal_order = list(nx.topological_sort(bn))
    cardinality_dict = {}

    for node in causal_order:
        parents = list(bn.predecessors(node))
        card = int(np_rng.integers(n_modmin, n_modmax + 1))
        cardinality_dict[node] = card

        cpd = sample_cpd(
            variable=node,
            variable_card=card,
            parents=parents,
            evidence_card=[cardinality_dict[p] for p in parents],
            np_rng=np_rng,
        )
        bn.add_cpds(cpd)

    # Verify CPD shapes, column sums, and that the graph is a valid DAG
    assert bn.check_model()

    return bn, cardinality_dict

def generate_random_bn(n_nodes, ratio_arc, n_modmin, n_modmax, np_rng):
    if ratio_arc == 0:
        return generate_simple_bn(n_nodes, n_modmin, n_modmax, np_rng)

    return generate_realistic_bn(n_nodes, ratio_arc, n_modmin, n_modmax, np_rng)
    
def sample_cpd(variable, variable_card, parents, evidence_card, np_rng):
    n_parent_configs = int(np.prod(evidence_card)) if evidence_card else 1

    values = np.array([
        np_rng.dirichlet(np_rng.uniform(0.2, 0.7, size=variable_card))
        for _ in range(n_parent_configs)
    ]).T

    if parents:
        return TabularCPD(
            variable=variable,
            variable_card=variable_card,
            values=values,
            evidence=parents,
            evidence_card=evidence_card,
        )
    else:
        return TabularCPD(
            variable=variable,
            variable_card=variable_card,
            values=values.reshape(variable_card, 1),
        )

def generate_general_pop(bn, n_samples, seed):
    sampler = BayesianModelSampling(bn)
    return sampler.forward_sample(size=n_samples, show_progress=False, seed = seed)